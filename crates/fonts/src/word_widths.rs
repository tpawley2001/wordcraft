//! Advance widths Word gives Verdana, Tahoma, Century Gothic, SimSun, Aptos, Aptos Display,
//! Trebuchet MS, Garamond, Consolas, Comic Sans MS, Corbel, Candara, Constantia, Tw Cen MT, Georgia,
//! Arial Black, Segoe UI, Bookman Old Style, Perpetua and Gill Sans MT when the font isn't installed: their text is drawn with a substitute, but each character keeps the width Word
//! gives it, so lines break where Word breaks them.

/// The advance (em) Word gives `c` in `family` (bold / italic) when that font isn't installed,
/// or `None` to keep the drawn substitute's advance. `family` is matched case-insensitively
/// ("Verdana", "Tahoma", "Century Gothic", "SimSun" or "宋体", "Aptos", "Aptos Display",
/// "Trebuchet MS", "Garamond", "Consolas", "Comic Sans MS", "Corbel", "Candara", "Constantia",
/// "Tw Cen MT", "Georgia", "Arial Black", "Segoe UI", "Bookman Old Style", "Perpetua",
/// "Gill Sans MT"). Consolas is fixed-pitch: every Windows-1252 character except the controls is
/// 0.55 em in every style. A style with no table of its own (Tahoma Italic, SimSun Bold,
/// Trebuchet MS Bold Italic) takes the regular widths: Word synthesises it from the regular
/// face with the same advances. Tw Cen MT was only measured in bold, so its other styles keep
/// the substitute's advances. Characters not in the table give `None`.
pub fn missing_font_advance(family: &str, bold: bool, italic: bool, c: char) -> Option<f64> {
    let family = family.trim();
    if family.eq_ignore_ascii_case("consolas") {
        // Fixed-pitch: Word's PDFs give every character 550/1000 em in every style.
        return cp1252_code(c).filter(|&code| code >= 0x20 && code != 0x7F).map(|_| 0.55);
    }
    let table = table(family, bold, italic)?;
    let code = cp1252_code(c)?;
    let i = table.binary_search_by_key(&code, |&(k, _)| k).ok()?;
    table.get(i).map(|&(_, w)| f64::from(w) / 1000.0)
}

/// The width table for `family` in a style, falling back to the regular one.
fn table(family: &str, bold: bool, italic: bool) -> Option<&'static [(u8, u16)]> {
    let is = |name: &str| family.eq_ignore_ascii_case(name);
    let (regular, b, i, bi): (_, Option<&'static [(u8, u16)]>, Option<&'static [(u8, u16)]>, Option<&'static [(u8, u16)]>) = if is("verdana") {
        (VERDANA, Some(VERDANA_BOLD), Some(VERDANA_ITALIC), Some(VERDANA_BOLD_ITALIC))
    } else if is("tahoma") {
        (TAHOMA, Some(TAHOMA_BOLD), None, None)
    } else if is("century gothic") {
        (CENTURY_GOTHIC, Some(CENTURY_GOTHIC_BOLD), Some(CENTURY_GOTHIC_ITALIC), None)
    } else if is("simsun") || family == "宋体" {
        (SIMSUN, None, None, None)
    } else if is("aptos") {
        (APTOS, Some(APTOS_BOLD), Some(APTOS_ITALIC), Some(APTOS_BOLD_ITALIC))
    } else if is("aptos display") {
        // Its own widths, not Aptos's (a space is 0.193 em, not 0.203).
        (APTOS_DISPLAY, Some(APTOS_DISPLAY_BOLD), None, None)
    } else if is("trebuchet ms") {
        (TREBUCHET_MS, Some(TREBUCHET_MS_BOLD), Some(TREBUCHET_MS_ITALIC), None)
    } else if is("garamond") {
        (GARAMOND, Some(GARAMOND_BOLD), None, None)
    } else if is("comic sans ms") {
        // Word slants the upright face: italic takes the upright widths, bold italic the bold.
        (COMIC_SANS_MS, Some(COMIC_SANS_MS_BOLD), Some(COMIC_SANS_MS), Some(COMIC_SANS_MS_BOLD))
    } else if is("corbel") {
        (CORBEL, Some(CORBEL_BOLD), Some(CORBEL_ITALIC), None)
    } else if is("candara") {
        (CANDARA, Some(CANDARA_BOLD), None, None)
    } else if is("constantia") {
        (CONSTANTIA, Some(CONSTANTIA_BOLD), Some(CONSTANTIA_ITALIC), None)
    } else if is("tw cen mt") {
        // Only bold was measured: the empty regular table leaves other styles the substitute's widths.
        (&[], Some(TW_CEN_MT_BOLD), None, None)
    } else if is("georgia") {
        (GEORGIA, Some(GEORGIA_BOLD), Some(GEORGIA_ITALIC), Some(GEORGIA_BOLD_ITALIC))
    } else if is("arial black") {
        (ARIAL_BLACK, None, None, None)
    } else if is("segoe ui") {
        // Only "Segoe UI" itself: Light, Semibold and Symbol are other faces with other widths.
        (SEGOE_UI, Some(SEGOE_UI_BOLD), Some(SEGOE_UI_ITALIC), None)
    } else if is("bookman old style") {
        (BOOKMAN_OLD_STYLE, Some(BOOKMAN_OLD_STYLE_BOLD), Some(BOOKMAN_OLD_STYLE_ITALIC), Some(BOOKMAN_OLD_STYLE_BOLD_ITALIC))
    } else if is("perpetua") {
        (PERPETUA, Some(PERPETUA_BOLD), None, None)
    } else if is("gill sans mt") {
        (GILL_SANS_MT, Some(GILL_SANS_MT_BOLD), None, None)
    } else {
        return None;
    };
    let styled = match (bold, italic) {
        (false, false) => None,
        (true, false) => b,
        (false, true) => i,
        (true, true) => bi,
    };
    Some(styled.unwrap_or(regular))
}

/// The Windows-1252 code of `c` (U+0020-U+00FF and the characters cp1252 puts at 0x80-0x9F).
fn cp1252_code(c: char) -> Option<u8> {
    let u = u32::from(c);
    if (0x20..=0x7E).contains(&u) || (0xA0..=0xFF).contains(&u) || matches!(u, 0x81 | 0x8D | 0x8F | 0x90 | 0x9D) {
        return u8::try_from(u).ok();
    }
    Some(match c {
        '\u{20AC}' => 0x80,
        '\u{201A}' => 0x82,
        '\u{0192}' => 0x83,
        '\u{201E}' => 0x84,
        '\u{2026}' => 0x85,
        '\u{2020}' => 0x86,
        '\u{2021}' => 0x87,
        '\u{02C6}' => 0x88,
        '\u{2030}' => 0x89,
        '\u{0160}' => 0x8A,
        '\u{2039}' => 0x8B,
        '\u{0152}' => 0x8C,
        '\u{017D}' => 0x8E,
        '\u{2018}' => 0x91,
        '\u{2019}' => 0x92,
        '\u{201C}' => 0x93,
        '\u{201D}' => 0x94,
        '\u{2022}' => 0x95,
        '\u{2013}' => 0x96,
        '\u{2014}' => 0x97,
        '\u{02DC}' => 0x98,
        '\u{2122}' => 0x99,
        '\u{0161}' => 0x9A,
        '\u{203A}' => 0x9B,
        '\u{0153}' => 0x9C,
        '\u{017E}' => 0x9E,
        '\u{0178}' => 0x9F,
        _ => return None,
    })
}

